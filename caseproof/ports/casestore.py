from typing import Protocol

from caseproof.domain.contracts import CaseSnapshot


class CaseStorePort(Protocol):
    def create(
        self, case_id: str | None = None, tenant_id: str = "demo", **metadata
    ) -> CaseSnapshot: ...
    def get(self, case_id: str, revision: int | None = None) -> CaseSnapshot: ...
    def publish(
        self, snapshot: CaseSnapshot, expected_revision: int, event: str = "updated"
    ) -> CaseSnapshot: ...
    def metadata(self, case_id: str) -> dict: ...
    def list_cases(self, tenant: str = "demo") -> list[dict]: ...
